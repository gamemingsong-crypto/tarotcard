def draw_cards(n: int):
    """สุ่มไพ่ n ใบ (ไม่ซ้ำ) พร้อมสุ่มทิศทาง (ตั้งตรง/กลับหัว)"""
    chosen = random.sample(DECK, n)
    result = []
    for card in chosen:
        orientation = "reversed" if random.random() < REVERSED_CHANCE else "upright"
        result.append((card, orientation))
    return result


def get_meaning(card, orientation: str) -> str:
    return card["upright"] if orientation == "upright" else card["reversed"]


def get_category_text(card, orientation: str, category: str) -> str:
    """สร้างข้อความคำทำนายที่โฟกัสหมวดหมู่ที่เลือก"""
    meaning = get_meaning(card, orientation)
    if category == "ภาพรวม":
        return meaning
    frame = random.choice(CATEGORY_INFO[category]["frames"])
    return f"{frame} {meaning}"


def get_advice(category: str, orientation: str) -> str:
    if category == "ภาพรวม" or category not in ADVICE:
        return random.choice(ADVICE_GENERAL[orientation])
    return random.choice(ADVICE[category][orientation])


def orientation_label(orientation: str) -> str:
    return "ตั้งตรง" if orientation == "upright" else "กลับหัว"
